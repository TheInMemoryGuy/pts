create or replace package body lead_jira_pkg as
    procedure create_jira_issue(
        p_lead_id        in number,
        p_issue_key       out varchar2,
        p_issue_url       out varchar2
    ) is
    begin
        -- Stub: call Jira REST API POST /rest/api/3/issue
        -- Store returned issue key and browse URL.
        p_issue_key := null;
        p_issue_url  := null;
    end;

    procedure add_jira_comment(
        p_lead_id        in number,
        p_comment_text   in clob
    ) is
    begin
        -- Stub: call Jira REST API POST /rest/api/3/issue/{issueIdOrKey}/comment
        null;
    end;

    procedure sync_lead_update(
        p_lead_id        in number,
        p_action_name    in varchar2,
        p_comment_text   in clob default null
    ) is
        l_issue_key varchar2(50);
    begin
        select jira_issue_key
          into l_issue_key
          from lead_request
         where lead_id = p_lead_id;

        if l_issue_key is null then
            create_jira_issue(p_lead_id => p_lead_id, p_issue_key => l_issue_key, p_issue_url => null);
        else
            add_jira_comment(p_lead_id => p_lead_id, p_comment_text => p_comment_text);
        end if;

        insert into jira_sync_log (lead_id, jira_issue_key, action_name, status, created_at)
        values (p_lead_id, l_issue_key, p_action_name, 'PENDING', systimestamp);
    exception
        when others then
            insert into jira_sync_log (lead_id, jira_issue_key, action_name, status, error_message, created_at)
            values (p_lead_id, l_issue_key, p_action_name, 'ERROR', sqlerrm, systimestamp);
            raise;
    end;
end lead_jira_pkg;
