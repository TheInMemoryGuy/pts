-- Oracle APEX Lead Tracker Starter
-- Tables, lookup data, and Jira sync stubs for an APEX-based lead tracking app.

-- ============================================================
-- 1) LOOKUP TABLES
-- ============================================================

create table product_catalog (
    product_id           number generated by default as identity primary key,
    product_name         varchar2(200) not null,
    product_family       varchar2(100),
    business_unit        varchar2(100),
    is_active            varchar2(1) default 'Y' not null check (is_active in ('Y','N')),
    created_at           timestamp default systimestamp not null,
    updated_at           timestamp
);

create unique index ux_product_catalog_name on product_catalog (upper(product_name));

create table lead_state_lu (
    state_code           varchar2(30) primary key,
    state_name           varchar2(100) not null,
    sort_order           number not null,
    is_terminal          varchar2(1) default 'N' not null check (is_terminal in ('Y','N'))
);

create table priority_lu (
    priority_code        varchar2(10) primary key,
    priority_name        varchar2(100) not null,
    sort_order           number not null
);

create table engagement_lu (
    engagement_code      varchar2(20) primary key,
    engagement_name      varchar2(100) not null,
    sort_order           number not null
);

create table readiness_lu (
    readiness_code       varchar2(30) primary key,
    readiness_name       varchar2(100) not null,
    sort_order           number not null
);

-- ============================================================
-- 2) CORE TABLES
-- ============================================================

create table lead_request (
    lead_id                  number generated by default as identity primary key,
    lead_number              varchar2(30) not null,
    customer_name            varchar2(255) not null,
    customer_account         varchar2(255),
    customer_contact_name    varchar2(255),
    customer_contact_email   varchar2(320),
    source_employee_name     varchar2(255) not null,
    source_employee_email    varchar2(320),
    product_primary_id       number,
    state_code               varchar2(30) not null,
    priority_code            varchar2(10) not null,
    engagement_code          varchar2(20) not null,
    readiness_code           varchar2(30) not null,
    use_case_summary         varchar2(4000),
    transcript_clob          clob,
    jira_issue_key           varchar2(50),
    jira_issue_url           varchar2(1000),
    jira_sync_status         varchar2(30) default 'PENDING' not null,
    jira_last_sync_at        timestamp,
    lead_owner               varchar2(255),
    created_by               varchar2(255),
    created_at               timestamp default systimestamp not null,
    updated_by               varchar2(255),
    updated_at               timestamp,
    constraint uq_lead_request_lead_number unique (lead_number),
    constraint fk_lead_product foreign key (product_primary_id) references product_catalog(product_id),
    constraint fk_lead_state foreign key (state_code) references lead_state_lu(state_code),
    constraint fk_lead_priority foreign key (priority_code) references priority_lu(priority_code),
    constraint fk_lead_engagement foreign key (engagement_code) references engagement_lu(engagement_code),
    constraint fk_lead_readiness foreign key (readiness_code) references readiness_lu(readiness_code)
);

create index ix_lead_request_state on lead_request(state_code);
create index ix_lead_request_priority on lead_request(priority_code);
create index ix_lead_request_product on lead_request(product_primary_id);
create index ix_lead_request_jira on lead_request(jira_issue_key);

create table lead_product_interest (
    lead_product_id          number generated by default as identity primary key,
    lead_id                  number not null,
    product_id               number not null,
    interest_level           varchar2(20) not null,
    created_at               timestamp default systimestamp not null,
    constraint fk_lpi_lead foreign key (lead_id) references lead_request(lead_id) on delete cascade,
    constraint fk_lpi_product foreign key (product_id) references product_catalog(product_id),
    constraint ck_lpi_interest check (interest_level in ('PRIMARY','SECONDARY','FUTURE'))
);

create unique index ux_lpi_unique on lead_product_interest (lead_id, product_id);

create table lead_interaction (
    interaction_id           number generated by default as identity primary key,
    lead_id                  number not null,
    interaction_type         varchar2(50) not null,
    interaction_notes        clob,
    transcript_clob          clob,
    author_name              varchar2(255),
    author_email             varchar2(320),
    jira_comment_id          varchar2(100),
    created_at               timestamp default systimestamp not null,
    constraint fk_interaction_lead foreign key (lead_id) references lead_request(lead_id) on delete cascade
);

create index ix_lead_interaction_lead on lead_interaction(lead_id);

create table lead_state_history (
    history_id               number generated by default as identity primary key,
    lead_id                  number not null,
    old_state_code           varchar2(30),
    new_state_code           varchar2(30) not null,
    changed_by               varchar2(255),
    changed_at               timestamp default systimestamp not null,
    change_reason            varchar2(4000),
    constraint fk_lsh_lead foreign key (lead_id) references lead_request(lead_id) on delete cascade
);

create index ix_lsh_lead on lead_state_history(lead_id);

create table jira_sync_log (
    sync_id                  number generated by default as identity primary key,
    lead_id                  number,
    jira_issue_key           varchar2(50),
    action_name              varchar2(50) not null,
    status                   varchar2(30) not null,
    request_payload          clob,
    response_payload         clob,
    error_message            varchar2(4000),
    created_at               timestamp default systimestamp not null
);

