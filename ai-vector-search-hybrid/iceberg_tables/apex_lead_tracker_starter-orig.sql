-- 4) SEQUENCES / NUMBERING
-- ============================================================

create sequence seq_lead_number start with 1000 increment by 1 nocache;

create or replace trigger bi_lead_request
before insert on lead_request
for each row
begin
    if :new.lead_number is null then
        :new.lead_number := 'L-' || to_char(seq_lead_number.nextval);
    end if;

    if :new.created_at is null then
        :new.created_at := systimestamp;
    end if;
end;
/

create or replace trigger bu_lead_request
before update on lead_request
for each row
begin
    :new.updated_at := systimestamp;
end;
/

